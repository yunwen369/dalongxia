# 层级后缀只出现在二级/三级行业名上（「白酒Ⅱ」「IT服务Ⅱ」「林业Ⅱ」），
# 一级名不带后缀，故归一化时统一剥离，避免映射表被迫为每个名字写两条。
_LEVEL_SUFFIX = re.compile(r"[ⅠⅡⅢⅣⅤ]+$")


def normalize_sw_name(name: Optional[str]) -> str:
    """归一化申万行业名：去空白、剥层级罗马数字后缀。

    Args:
        name: 上游原始行业名，可能为 ``None``/``-``/空串。

    Returns:
        str: 归一化后的行业名；无有效内容时返回空串。
    """
    text = (name or "").strip()
    if text in ("", "-", "--"):
        return ""
    return _LEVEL_SUFFIX.sub("", text).strip()


def l1_of(name: Optional[str]) -> str:
    """把上游行业名映射到申万一级。

    Args:
        name: 上游行业名（含 ``Ⅱ`` 后缀亦可）。

    Returns:
        str: 申万一级名；无法映射时返回 :data:`UNCLASSIFIED`。
    """
    key = normalize_sw_name(name)
    if not key:
        return UNCLASSIFIED
    return SW_L2_TO_L1.get(key, UNCLASSIFIED)


def l2_of(name: Optional[str]) -> str:
    """把上游行业名归一化为二级展示名（保留原语义，仅去后缀）。

    上游已直接给二级名，因此二级即归一化后的原名；无法映射时与一级同为
    :data:`UNCLASSIFIED`，保证「一级 = 二级」的兜底形态符合 PRD §6.2。

    Args:
        name: 上游行业名。

    Returns:
        str: 二级展示名。
    """
    key = normalize_sw_name(name)
    return key or UNCLASSIFIED
